#!/usr/bin/env python3
"""Verify or reproducibly rebuild the canonical Pokémon Red ROM artifacts."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "pokered"
ARTIFACTS = ROOT / "artifacts" / "pokered"
MANIFEST_PATH = ARTIFACTS / "build-manifest.json"
SYMBOL_RE = re.compile(r"^([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4}) (\S+)$")
CONSTANT_RE = re.compile(r"^([0-9A-Fa-f]{2}) (\S+)$")
PINNED_SOURCE = "405b6246372d7e5a2cb029cbb65219b13286b8c9"
PINNED_RGBDS = "3b1606c63c1671fd6675747507fe95d7f72da2d9"


def digest(path: Path, algorithm: str) -> str:
    value = hashlib.new(algorithm)
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def line_count(path: Path) -> int:
    with path.open("rb") as stream:
        return sum(1 for _ in stream)


def verify_file(path: Path, record: dict[str, object]) -> None:
    if not path.is_file():
        raise AssertionError(f"missing artifact: {path.relative_to(ROOT)}")
    expected_size = int(record["size"])
    actual_size = path.stat().st_size
    if actual_size != expected_size:
        raise AssertionError(f"{path.name}: size {actual_size}, expected {expected_size}")
    if "lines" in record:
        actual_lines = line_count(path)
        expected_lines = int(record["lines"])
        if actual_lines != expected_lines:
            raise AssertionError(f"{path.name}: lines {actual_lines}, expected {expected_lines}")
    actual_sha256 = digest(path, "sha256")
    if actual_sha256 != record["sha256"]:
        raise AssertionError(
            f"{path.name}: sha256 {actual_sha256}, expected {record['sha256']}"
        )


def load_manifest() -> dict[str, object]:
    manifest = json.loads(MANIFEST_PATH.read_text())
    if manifest["pokered_commit"] != PINNED_SOURCE:
        raise AssertionError("build manifest source revision drift")
    if manifest["rgbds_commit"] != PINNED_RGBDS:
        raise AssertionError("build manifest RGBDS revision drift")
    return manifest


def verify_symbols(path: Path) -> dict[str, tuple[int, int]]:
    symbols: dict[str, tuple[int, int]] = {}
    lines = path.read_text().splitlines()
    if not lines or lines[0] != "; File generated by rgblink":
        raise AssertionError("unexpected .sym header")
    for number, line in enumerate(lines[1:], 2):
        match = SYMBOL_RE.fullmatch(line)
        constant = CONSTANT_RE.fullmatch(line)
        if match:
            bank = int(match.group(1), 16)
            address = int(match.group(2), 16)
            symbol = match.group(3)
        elif constant:
            bank = -1
            address = int(constant.group(1), 16)
            symbol = constant.group(2)
        else:
            raise AssertionError(f"malformed symbol line {number}: {line!r}")
        if symbol in symbols:
            raise AssertionError(f"duplicate symbol {symbol!r} at line {number}")
        symbols[symbol] = (bank, address)

    required = {
        "InitOpponent",
        "InitBattle",
        "_InitBattleCommon",
        "StartBattle",
        "EndOfBattle",
        "Random_",
        "BattleRandom",
        "DelayFrame",
        "VBlank",
        "wBattleResult",
        "wIsInBattle",
    }
    missing = sorted(required - symbols.keys())
    if missing:
        raise AssertionError(f"missing required symbols: {', '.join(missing)}")
    return symbols


def verify_rom(path: Path, record: dict[str, object]) -> None:
    verify_file(path, record)
    actual_sha1 = digest(path, "sha1")
    if actual_sha1 != record["sha1"]:
        raise AssertionError(f"{path.name}: sha1 {actual_sha1}, expected {record['sha1']}")


def verify_entry_metadata(manifest: dict[str, object], symbols: dict[str, tuple[int, int]]) -> None:
    records = manifest.get("entry_bytes")
    if not isinstance(records, list) or not records:
        raise AssertionError("missing canonical entry-byte witnesses")
    seen: set[str] = set()
    for record in records:
        if not isinstance(record, dict):
            raise AssertionError("malformed entry-byte record")
        symbol = str(record["symbol"])
        if symbol in seen:
            raise AssertionError(f"duplicate entry-byte witness: {symbol}")
        seen.add(symbol)
        bank = int(record["bank"])
        address = int(record["address"])
        if symbols.get(symbol) != (bank, address):
            raise AssertionError(f"{symbol}: entry-byte address differs from retained symbols")
        offset = address if address < 0x4000 else bank * 0x4000 + address - 0x4000
        if int(record["rom_offset"]) != offset:
            raise AssertionError(f"{symbol}: incorrect physical ROM offset")
        try:
            payload = bytes.fromhex(str(record["hex"]))
        except ValueError as error:
            raise AssertionError(f"{symbol}: malformed entry-byte hex") from error
        if len(payload) != 16:
            raise AssertionError(f"{symbol}: expected a 16-byte witness")


def verify_entry_bytes(path: Path, manifest: dict[str, object]) -> None:
    rom = path.read_bytes()
    records = manifest["entry_bytes"]
    assert isinstance(records, list)
    for record in records:
        assert isinstance(record, dict)
        payload = bytes.fromhex(str(record["hex"]))
        offset = int(record["rom_offset"])
        if rom[offset : offset + len(payload)] != payload:
            raise AssertionError(f"{record['symbol']}: canonical entry bytes differ")


def command_version(command: str) -> str:
    executable = shutil.which(command)
    if executable is None:
        raise AssertionError(f"{command} not found; enter the pinned Nix development shell")
    return subprocess.check_output([executable, "--version"], text=True).strip()


def rebuild(manifest: dict[str, object], jobs: int, output_rom: Path | None = None) -> None:
    version = command_version("rgbasm")
    if version != "rgbasm v1.0.2":
        raise AssertionError(f"unexpected RGBDS: {version}")
    if shutil.which("make") is None:
        raise AssertionError("make not found; enter the pinned Nix development shell")

    with tempfile.TemporaryDirectory(prefix="pokered-build-") as temporary:
        checkout = Path(temporary) / "pokered"
        shutil.copytree(SOURCE, checkout)
        command = ["make", "-C", str(checkout), f"-j{jobs}", "pokered.gbc"]
        completed = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        if completed.returncode:
            sys.stderr.write(completed.stdout)
            raise AssertionError(f"canonical build failed with exit code {completed.returncode}")

        rom_record = manifest["rom"]
        symbol_record = manifest["symbols"]
        map_record = manifest["map"]
        assert isinstance(rom_record, dict)
        assert isinstance(symbol_record, dict)
        assert isinstance(map_record, dict)
        generated_rom = checkout / str(rom_record["file"])
        verify_rom(generated_rom, rom_record)
        verify_entry_bytes(generated_rom, manifest)

        generated_symbol = checkout / str(symbol_record["file"])
        generated_map = checkout / str(map_record["file"])
        verify_file(generated_symbol, symbol_record)
        verify_file(generated_map, map_record)
        if generated_symbol.read_bytes() != (ARTIFACTS / "pokered.sym").read_bytes():
            raise AssertionError("rebuilt symbol file differs from retained artifact")
        if generated_map.read_bytes() != (ARTIFACTS / "pokered.map").read_bytes():
            raise AssertionError("rebuilt map file differs from retained artifact")

        if output_rom is not None:
            output_rom.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(generated_rom, output_rom)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rebuild", action="store_true", help="build in a temporary checkout and compare")
    parser.add_argument("--rom", type=Path, help="verify a caller-supplied ROM without retaining it")
    parser.add_argument(
        "--output-rom",
        type=Path,
        help="copy a verified temporary rebuild here for downstream tests",
    )
    parser.add_argument("--jobs", type=int, default=4)
    args = parser.parse_args()

    manifest = load_manifest()
    symbol_record = manifest["symbols"]
    map_record = manifest["map"]
    rom_record = manifest["rom"]
    assert isinstance(symbol_record, dict)
    assert isinstance(map_record, dict)
    assert isinstance(rom_record, dict)

    symbol_path = ARTIFACTS / str(symbol_record["file"])
    verify_file(symbol_path, symbol_record)
    verify_file(ARTIFACTS / str(map_record["file"]), map_record)
    symbols = verify_symbols(symbol_path)
    verify_entry_metadata(manifest, symbols)

    if args.output_rom and not args.rebuild:
        raise AssertionError("--output-rom requires --rebuild")
    if args.rom:
        verify_rom(args.rom, rom_record)
        verify_entry_bytes(args.rom, manifest)
    if args.rebuild:
        rebuild(manifest, args.jobs, args.output_rom)

    mode = "rebuilt" if args.rebuild else "retained"
    print(
        f"PASS canonical Red {mode}: symbols={len(symbols)}, "
        f"rom_sha1={rom_record['sha1']}, rgbds={manifest['rgbds_version']}"
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except AssertionError as error:
        print(f"FAIL {error}", file=sys.stderr)
        raise SystemExit(1)
